// Source template: package.mjs supplies the exact release resource hashes.
function createServiceWorker521({revision,assets,hashes,appVersion}) {
  return `// Generated by scripts/package.mjs; never edit this generated file.
const APP_VERSION = ${JSON.stringify(appVersion)};
const REVISION = ${JSON.stringify(revision)};
const CACHE_PREFIX = 'qicheng-static-' + encodeURIComponent(new URL(self.registration.scope).pathname) + '-';
const CACHE_NAME = CACHE_PREFIX + 'v5-' + REVISION;
const PRECACHE = ${JSON.stringify(assets)};
const HASHES = ${JSON.stringify(hashes)};
const URLS = new Set(PRECACHE.map(path => new URL(path,self.registration.scope).href));
let installProgress = {type:'UPDATE_CACHE_PROGRESS',revision:REVISION,done:0,total:PRECACHE.length};
let activationSession = null;
async function scopedClients() {
  return (await self.clients.matchAll({type:'window',includeUncontrolled:true})).filter(client=>client.url?.startsWith(self.registration.scope));
}
async function announce(message) { for(const client of await scopedClients())client.postMessage(message); }
async function digest(response) {
  const bytes=await response.clone().arrayBuffer();
  return Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes)),byte=>byte.toString(16).padStart(2,'0')).join('');
}
self.addEventListener('install',event => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE_NAME);
      await announce(installProgress);
      // Four real downloads at a time; hashes reject a mixed/incomplete deployment.
      for(let offset=0;offset<PRECACHE.length;offset+=4){
        const batch=PRECACHE.slice(offset,offset+4);
        const results=await Promise.allSettled(batch.map(async path=>{
          let lastError;
          for(let attempt=0;attempt<2;attempt++)try {
            const url=new URL(path,self.registration.scope).href;
            const response=await fetch(new Request(url,{cache:'reload'}));
            if(!response.ok || response.type==='opaque')throw new Error('HTTP '+response.status);
            if(await digest(response)!==HASHES[path])throw new Error('资源校验不一致，请等待完整版本上传后重试');
            await cache.put(url,response);return;
          }catch(error){lastError=error;}
          throw new Error(path+' — '+lastError.message);
        }));
        const failed=results.find(item=>item.status==='rejected');
        if(failed)throw failed.reason;
        installProgress={...installProgress,done:offset+batch.length};
        await announce(installProgress);
      }
      await cache.put(new URL('__release_ready__',self.registration.scope).href,new Response(REVISION));
      await announce({type:'UPDATE_CACHE_READY',revision:REVISION,appVersion:APP_VERSION,total:PRECACHE.length});
    } catch(error) {
      await caches.delete(CACHE_NAME);
      await announce({type:'UPDATE_CACHE_FAILED',revision:REVISION,detail:error.message});
      throw error;
    }
  })());
});
self.addEventListener('activate',event => {
  event.waitUntil((async () => {
    // Retain the preceding complete cache for interrupted transitions. Older
    // caches can be discarded without touching the user's IndexedDB.
    const older=(await caches.keys()).filter(name=>name.startsWith(CACHE_PREFIX)&&name!==CACHE_NAME);
    for(const name of older.slice(0,-1))await caches.delete(name);
    // Do not claim an uncontrolled page loaded from another resource version.
    await announce({type:'UPDATE_ACTIVATED',revision:REVISION,appVersion:APP_VERSION});
  })());
});
async function abortActivation(reason) {
  const session=activationSession;if(!session)return;
  activationSession=null;clearTimeout(session.timer);
  await announce({type:'UPDATE_ABORTED',requestId:session.id,detail:reason});
}
async function activateWhenReady() {
  const session=activationSession;if(!session||session.pending.size)return;
  const clients=await scopedClients();
  if(clients.length!==session.clients.size || clients.some(client=>!session.clients.has(client.id)))return abortActivation('窗口发生变化，请稍后重试。');
  const cache=await caches.open(CACHE_NAME);
  if(!await cache.match(new URL('__release_ready__',self.registration.scope).href))return abortActivation('新版资源尚未完整准备。');
  clearTimeout(session.timer);
  await announce({type:'UPDATE_ACTIVATING',requestId:session.id,revision:REVISION});
  await self.skipWaiting();
}
self.addEventListener('message',event => {
  const message=event.data||{};
  event.waitUntil((async()=>{
    const clients=await scopedClients();
    if(!event.source?.id || !clients.some(client=>client.id===event.source.id))return;
    if(message.type==='GET_RELEASE_INFO') {event.source.postMessage({type:'UPDATE_RELEASE_INFO',revision:REVISION,appVersion:APP_VERSION});return;}
    if(message.type==='GET_UPDATE_PROGRESS') {event.source.postMessage(installProgress);return;}
    if(message.type==='ACTIVATE_UPDATE') {
      if(activationSession)return;
      // 5.2.0 knows only ACTIVATE_UPDATE. It flushes its own edits before sending
      // this message; allow its single saved window, but never disturb peers.
      if(message.protocol!==2) {
        if(clients.length!==1){event.source.postMessage({type:'UPDATE_ABORTED',detail:'请关闭其他启程窗口，再保存并更新。'});return;}
        const cache=await caches.open(CACHE_NAME);
        if(await cache.match(new URL('__release_ready__',self.registration.scope).href))await self.skipWaiting();
        return;
      }
      const id=String(message.requestId||'');if(!id)return;
      activationSession={id,pending:new Set(clients.map(client=>client.id)),clients:new Set(clients.map(client=>client.id)),timer:null};
      activationSession.timer=setTimeout(()=>abortActivation('有窗口未响应。请关闭闲置窗口后重试，当前版本继续可用。'),15000);
      for(const client of clients)client.postMessage({type:'PREPARE_APP_UPDATE',requestId:id,revision:REVISION,initiator:event.source.id===client.id});
      return;
    }
    if(message.type==='APP_UPDATE_READY' && activationSession?.id===message.requestId && activationSession.pending.has(event.source.id)) {
      if(!message.ready)return abortActivation(message.detail||'其他窗口正在编辑或尚未保存，请完成后重试。');
      activationSession.pending.delete(event.source.id);await activateWhenReady();
    }
  })());
});
self.addEventListener('fetch',event => {
  const request = event.request, url = new URL(request.url);
  if(request.method !== 'GET' || url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  if(request.cache === 'no-store') return;
  if(request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      return await cache.match(new URL('index.html',self.registration.scope).href) || new Response('离线程序资源缺失，请联网后重新检查应用更新。',{status:503});
    })()); return;
  }
  const cleanURL = new URL(url); cleanURL.search = ''; cleanURL.hash = '';
  if(!URLS.has(cleanURL.href)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Never fetch a possibly newer module into an older page on a cache miss.
    return await cache.match(cleanURL.href) || new Response('此版本程序资源缺失，请联网检查更新。',{status:503});
  })());
});
`;
}
export {createServiceWorker521};
